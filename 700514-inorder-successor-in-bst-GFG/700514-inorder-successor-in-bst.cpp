class Solution {
  public:
    int inOrderSuccessor(Node *root, Node *k) {
        // code here
        int ans = -1;
        Node* curr = root;
        while(curr){
            if(curr->data > k->data){
                ans = curr->data;
                curr = curr->left;
            }else{
                curr = curr->right;
            }
        }
    return ans;    
    }
};

